def scenario_header(scenario: Scenario) -> str:
    refs = "\n".join(f"- {ref.get('title', '')}: {ref.get('url', '')}" for ref in scenario.source_refs)
    tests = ", ".join(scenario.primary_tests)
    return f"""场景标题：{scenario.title}
领域：{scenario.domain}
测试重点：{tests}
来源引用：
{refs or "- 无"}
"""


